//! (phase 5, P5-WEBHOOK-2, D-320, C-909) Connect of a send-mode secret-link app (an outgoing
//! webhook): the org switch, the configuration and the secrets the person enters, validated with
//! `aurora-webhook` and the connection's rate ceiling, then added to the sealed credential
//! (`secret_values`, `signing_secret`) and stored as the connection's `config`. A generated
//! signing secret is returned once. Nothing is sent to the receiver at connect.
use super::*;
use crate::domains::outgoing_webhooks::service as wh;
use crate::domains::tenancy::dto::OrgSettings;
use aurora_registry::manifest::SecretLinkMode;

/// What connect gathered for an outgoing webhook.
pub(super) struct Gathered {
    /// The configuration to store; `None` on a reconnect that keeps the one it has.
    pub config_json: Option<Value>,
    /// A signing secret generated by this connect, for the response.
    pub generated: Option<String>,
}

pub(super) async fn prepare(
    ctx: &Ctx<'_>,
    g: &mut super::Gathered,
    body: Option<&Value>,
) -> Result<(), ConnectErr> {
    let send = ctx
        .app
        .secret_link
        .as_ref()
        .is_some_and(|s| s.mode() == SecretLinkMode::Send);
    if !send {
        return match body {
            None => Ok(()),
            Some(_) => Err(ConnectErr::Api(ApiError::invalid_request(
                "Invalid request.",
                vec![aurora_core::FieldError::new(
                    "/webhook",
                    "only an outgoing webhook takes a webhook configuration",
                )],
            ))),
        };
    }
    let settings = wh::org_settings(ctx.state, ctx.t.org).await?;
    if !OrgSettings::outgoing_webhooks_enabled(&settings) {
        return Err(ConnectErr::Api(wh::disabled()));
    }
    // A reconnect starts from the secrets the connection has.
    let (secrets, signing) = match &ctx.reconnect {
        Some(r) => {
            let c = wh::open_credentials(ctx.state, r).await?;
            (
                c.get("secret_values")
                    .and_then(Value::as_object)
                    .cloned()
                    .unwrap_or_default(),
                c.get("signing_secret")
                    .and_then(Value::as_str)
                    .map(str::to_owned),
            )
        }
        None => (Map::new(), None),
    };
    let (secrets, signing, config_json, generated) = match body {
        Some(b) => {
            let e = wh::apply(
                wh::ceiling(ctx.state, &settings),
                b.clone(),
                secrets,
                signing,
                ctx.reconnect.is_none(),
            )?;
            let cfg = serde_json::to_value(&e.config)
                .map_err(|_| ApiError::internal("Internal error."))?;
            (e.secrets, e.signing, Some(cfg), e.generated)
        }
        None if ctx.reconnect.is_some() => (secrets, signing, None, None),
        None => {
            return Err(ConnectErr::Api(wh::config_invalid(vec![
                aurora_webhook::FieldError {
                    path: "/webhook".into(),
                    code: "template_syntax",
                },
            ])));
        }
    };
    if !secrets.is_empty() {
        g.credentials
            .insert("secret_values".into(), Value::Object(secrets));
    }
    if let Some(s) = signing {
        g.credentials
            .insert("signing_secret".into(), Value::String(s));
    }
    g.webhook = Some(Gathered {
        config_json,
        generated,
    });
    Ok(())
}
