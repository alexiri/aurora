static LOCAL_COUNTERS: std::sync::OnceLock<aurora_counters::MemoryStore> =
    std::sync::OnceLock::new();

/// One all-or-nothing take of both windows on the keys the gateway uses (`gw:wh:<id>:…`).
async fn take(state: &AppState, id: Uuid, per_minute: u32, per_day: u32) -> Result<(), ApiError> {
    use aurora_counters::{CounterStore, Fallback, Period, Verdict, WindowUnit};
    let units = [
        WindowUnit {
            key: format!("gw:wh:{id}:minute"),
            period: Period::Minute,
            limit: u64::from(per_minute),
            cost: 1,
        },
        WindowUnit {
            key: format!("gw:wh:{id}:day"),
            period: Period::Day,
            limit: u64::from(per_day),
            cost: 1,
        },
    ];
    let local = || LOCAL_COUNTERS.get_or_init(aurora_counters::MemoryStore::new);
    let unavailable = || ApiError::counter_unavailable("api_management");
    let verdict = match state.counters.management() {
        Some(c) => match c.consume(&units).await {
            Ok(v) => v,
            Err(Fallback::Local) => local()
                .fixed_window_consume(&units)
                .await
                .map_err(|_| unavailable())?,
            Err(Fallback::Closed) => return Err(unavailable()),
        },
        None => local()
            .fixed_window_consume(&units)
            .await
            .map_err(|_| unavailable())?,
    };
    match verdict {
        Verdict::Allowed => Ok(()),
        Verdict::Refused { retry_after, .. } => {
            let secs = (retry_after.as_secs() + u64::from(retry_after.subsec_nanos() > 0)).max(1);
            Err(ApiError::new(
                http::StatusCode::TOO_MANY_REQUESTS,
                "webhook_rate_limited",
                format!("This webhook's send limit is reached. Retry after {secs} seconds."),
            )
            .with_retry_after(secs)
            .with_details(json!({ "retry_after_secs": secs })))
        }
    }
}

fn truncate_utf8(b: &[u8], max: usize) -> (String, bool) {
    if b.len() <= max {
        return (String::from_utf8_lossy(b).into_owned(), false);
    }
    let mut end = max;
    while end > 0 && (b[end] & 0xC0) == 0x80 {
        end -= 1;
    }
    (String::from_utf8_lossy(&b[..end]).into_owned(), true)
}

/// `POST /v1/connections/{id}/webhook/test`: the person sends (or dry-runs) the stored webhook
/// through the same renderer, destination guard, redirect rule and rate counters as the gateway.
pub async fn test(
    state: &AppState,
    caller: &Caller,
    id: Uuid,
    req: TestRequest,
) -> Result<TestResponse, ApiError> {
    let (row, config) = load(state, caller, id).await?;
    let settings = org_settings(state, row.org_id).await?;
    if !OrgSettings::outgoing_webhooks_enabled(&settings) {
        return Err(disabled());
    }
    if row.status != "active" {
        return Err(ApiError::new(
            http::StatusCode::CONFLICT,
            "connection_not_active",
            "This webhook is not active.",
        ));
    }
    let creds = open_credentials(state, &row).await?;
    let secrets = secrets_of(&creds);
    let names = aurora_webhook::secret_names_used(&config);
    let compiled = compile(&config, &names)?;
    if serde_json::to_vec(&req.values).map_or(0, |v| v.len()) > WEBHOOK_VALUES_MAX {
        return Err(ApiError::new(
            http::StatusCode::PAYLOAD_TOO_LARGE,
            "values_too_large",
            "The slot values are too large.",
        ));
    }
    let checked = aurora_webhook::check_values(&compiled, &req.values)
        .map_err(|e| invalid_slot(&e.slot, e.rule.as_str()))?;
    if req.dry_run {
        let r = aurora_webhook::render_masked(&compiled, &checked).map_err(render_err)?;
        let p = rendered_to_preview(&r, config.method.as_str());
        return Ok(TestResponse {
            status: None,
            content_type: Some(p.content_type),
            body: Some(p.body),
            truncated: None,
            delivery_id: None,
            method: Some(p.method),
            headers: Some(p.headers),
        });
    }
    let eff =
        aurora_webhook::effective_rate(instance_limits(state), org_caps(&settings), &config.rate);
    take(state, id, eff.per_minute, eff.per_day).await?;
    let sv = SecretValues(
        secrets
            .iter()
            .filter_map(|(k, v)| v.as_str().map(|s| (k.clone(), s.to_owned())))
            .collect::<BTreeMap<_, _>>(),
    );
    let rendered = aurora_webhook::render(&compiled, &checked, &sv).map_err(render_err)?;
    let url = creds
        .get("url")
        .and_then(Value::as_str)
        .ok_or_else(|| ApiError::internal("Stored credentials are unreadable."))?
        .to_owned();
    let signing = config.signing.then(|| signing_of(&creds)).flatten();
    let delivery = Uuid::now_v7();
    let reply = super::send::post(
        state,
        &url,
        &config,
        &rendered,
        signing.as_deref(),
        delivery,
    )
    .await?;
    // The echo check: the URL, its path-with-query and every secret (SEC-127).
    let mut needles = super::send::url_needles(&url);
    for s in sv.0.values().chain(signing.iter()) {
        if s.len() >= NEEDLE_MIN {
            needles.push(s.clone());
        }
    }
    let (body_text, truncated) = truncate_utf8(&reply.body, TEST_BODY_MAX);
    if needles.iter().any(|n| {
        body_text.contains(n.as_str())
            || reply
                .content_type
                .as_deref()
                .is_some_and(|c| c.contains(n.as_str()))
    }) {
        return Err(ApiError::new(
            http::StatusCode::BAD_GATEWAY,
            "upstream_echoed_credential",
            "The receiver answered with the webhook's address or a secret, so the response was withheld.",
        ));
    }
    let ev = crate::audit::AuditEvent::by(caller, "webhook.test_sent")
        .org(row.org_id)
        .target("connection", id)
        .metadata(json!({
            "connection_id": id, "status": reply.status, "delivery_id": delivery.to_string(),
        }));
    crate::audit::record(state, ev);
    Ok(TestResponse {
        status: Some(reply.status),
        content_type: reply.content_type,
        body: Some(body_text),
        truncated: Some(truncated),
        delivery_id: Some(delivery.to_string()),
        method: None,
        headers: None,
    })
}

async fn discard_sealed(state: &AppState, c: &SealContext, r: &SecretRef) {
    if let Err(e) = state
        .vault
        .discard(c, r, aurora_secrets::ValueSource::Managed)
        .await
    {
        tracing::warn!(error = %e, "discarding connection credentials failed");
    }
}
