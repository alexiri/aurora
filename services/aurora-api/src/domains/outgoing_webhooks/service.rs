/// Longest secret value and signing secret.
const SECRET_VALUE_MAX: usize = 4 * 1024;
/// Bytes of the receiver's answer a send test returns.
const TEST_BODY_MAX: usize = 4 * 1024;
/// Shortest secret that is searched for in an answer.
const NEEDLE_MIN: usize = 6;

// ---- errors ----------------------------------------------------------------------------------

/// 422 `webhook_config_invalid` with the failing paths and codes (C-909).
pub(crate) fn config_invalid(errs: Vec<aurora_webhook::FieldError>) -> ApiError {
    let fields: Vec<Value> = errs
        .iter()
        .map(|e| json!({ "path": e.path, "code": e.code }))
        .collect();
    ApiError::unprocessable(
        "webhook_config_invalid",
        "The webhook's configuration is not valid.",
    )
    .with_details(json!({ "fields": fields }))
}

fn invalid_one(path: &str, code: &'static str) -> ApiError {
    config_invalid(vec![aurora_webhook::FieldError {
        path: path.to_owned(),
        code,
    }])
}

fn invalid_slot(slot: &str, rule: &str) -> ApiError {
    ApiError::unprocessable(
        "invalid_slot",
        format!("The value of `{slot}` is not accepted ({rule})."),
    )
    .with_details(json!({ "slot": slot, "rule": rule }))
}

pub(crate) fn disabled() -> ApiError {
    ApiError::new(
        http::StatusCode::FORBIDDEN,
        "outgoing_webhooks_disabled",
        "Outgoing webhooks are turned off for this organization.",
    )
}

