pub async fn get(state: &AppState, caller: &Caller, id: Uuid) -> Result<WebhookView, ApiError> {
    let (row, config) = load(state, caller, id).await?;
    let creds = open_credentials(state, &row).await?;
    let settings = org_settings(state, row.org_id).await?;
    Ok(view_of(state, &row, &settings, config, &secrets_of(&creds)))
}

pub async fn put(
    state: &AppState,
    caller: &Caller,
    id: Uuid,
    body: Value,
) -> Result<PutWebhookResponse, ApiError> {
    let (row, _) = load(state, caller, id).await?;
    let settings = org_settings(state, row.org_id).await?;
    let creds = open_credentials(state, &row).await?;
    let edited = apply(
        ceiling(state, &settings),
        body,
        secrets_of(&creds),
        signing_of(&creds),
        false,
    )?;
    let config_json =
        serde_json::to_value(&edited.config).map_err(|_| ApiError::internal("Internal error."))?;
    let mut tx = crate::audit::begin(state).await?;
    let mut discard: Option<(SealContext, SecretRef)> = None;
    if edited.secrets_changed {
        let (cref, version) = repo::credentials_state(&mut *tx, id)
            .await?
            .ok_or_else(|| ApiError::not_found("Connection not found."))?;
        let new_creds = with_secrets(creds.clone(), &edited.secrets, edited.signing.as_deref());
        let bytes =
            serde_json::to_vec(&new_creds).map_err(|_| ApiError::internal("Internal error."))?;
        let sctx = seal_context(&row);
        let sref = state
            .vault
            .seal(&sctx, aurora_core::Secret::new(bytes))
            .await
            .map_err(secret_err)?;
        let mut keys: Vec<String> = new_creds.keys().cloned().collect();
        keys.sort_unstable();
        let ok = repo::replace_credentials_and_config(
            &mut *tx,
            id,
            version,
            &sref.to_column(),
            &keys,
            &config_json,
        )
        .await?;
        if !ok {
            discard_sealed(state, &sctx, &sref).await;
            return Err(ApiError::conflict(
                "connection_changed",
                "The connection changed while it was edited. Reload it and try again.",
            ));
        }
        if let Ok(old) = cref.parse::<SecretRef>() {
            discard = Some((sctx, old));
        }
    } else {
        repo::set_config(&mut *tx, id, &config_json).await?;
    }
    aurora_db::repo::credentials::notify_gateway_invalidate(&mut *tx, "connection", id).await?;
    let names: Vec<&String> = edited.secrets.keys().collect();
    let ev = crate::audit::AuditEvent::by(caller, "connection.webhook.update")
        .org(row.org_id)
        .target("connection", id)
        .metadata(json!({
            "app_id": row.app_id, "label": row.label,
            "secret_value_names": names,
            "secrets_changed": edited.secrets_changed,
            "signing": edited.signing.is_some(),
            "signing_secret_generated": edited.generated.is_some(),
        }));
    crate::audit::commit_critical(tx, &ev).await?;
    if let Some((ctx, old)) = discard {
        discard_sealed(state, &ctx, &old).await;
    }
    let row = repo::get(&state.pool, id)
        .await?
        .ok_or_else(|| ApiError::not_found("Connection not found."))?;
    Ok(PutWebhookResponse {
        view: view_of(state, &row, &settings, edited.config, &edited.secrets),
        signing_secret: edited.generated,
    })
}

fn compile(config: &WebhookConfig, names: &[String]) -> Result<CompiledConfig, ApiError> {
    aurora_webhook::validate(config, names).map_err(config_invalid)
}

fn rendered_to_preview(r: &aurora_webhook::Rendered, method: &str) -> PreviewResponse {
    PreviewResponse {
        method: method.to_owned(),
        content_type: r.content_type.clone(),
        headers: r.headers.iter().map(|(n, _)| n.clone()).collect(),
        body: String::from_utf8_lossy(&r.body).into_owned(),
    }
}

fn render_err(e: aurora_webhook::RenderError) -> ApiError {
    match e {
        aurora_webhook::RenderError::TooLarge => ApiError::new(
            http::StatusCode::PAYLOAD_TOO_LARGE,
            "rendered_too_large",
            "The rendered message is larger than the gateway sends.",
        ),
        _ => ApiError::unprocessable(
            "webhook_config_invalid",
            "A secret value the template uses is missing.",
        ),
    }
}

/// `POST /v1/apps/webhook/webhook-preview`: no network.
pub fn preview(body: Value) -> Result<PreviewResponse, ApiError> {
    let Some(Value::Object(mut req)) = Some(body) else {
        return Err(invalid_one("", "invalid_shape"));
    };
    let Some(Value::Object(mut cfg)) = req.remove("config") else {
        return Err(invalid_one("/config", "invalid_shape"));
    };
    let names: Vec<String> = match cfg.remove("secret_value_names") {
        None | Some(Value::Null) => Vec::new(),
        Some(v) => serde_json::from_value(v)
            .map_err(|_| invalid_one("/config/secret_value_names", "invalid_shape"))?,
    };
    let config = parse_config(Value::Object(cfg))?;
    let compiled = compile(&config, &names)?;
    let values = req.remove("values").unwrap_or_else(|| json!({}));
    let checked = aurora_webhook::check_values(&compiled, &values)
        .map_err(|e| invalid_slot(&e.slot, e.rule.as_str()))?;
    let r = aurora_webhook::render_masked(&compiled, &checked).map_err(render_err)?;
    Ok(rendered_to_preview(&r, config.method.as_str()))
}

/// `GET /v1/apps/{app}/webhook-presets`: the presets of the installed package version.
pub async fn presets(
    state: &AppState,
    app_id: &str,
) -> Result<Vec<aurora_webhook::WebhookPreset>, ApiError> {
    let snap = crate::domains::plugins::registry::active_typed(state)
        .await?
        .ok_or_else(|| ApiError::not_found("App not found."))?;
    let (app, pkg) = crate::domains::apps::service::find_app(&snap, app_id)
        .map_err(|_| ApiError::not_found("App not found."))?;
    if app
        .secret_link
        .as_ref()
        .is_none_or(|s| s.mode() != aurora_registry::manifest::SecretLinkMode::Send)
    {
        return Err(ApiError::not_found("This app has no webhook presets."));
    }
    let bytes = aurora_db::repo::plugins::get_blob(&state.pool, &pkg.digest, "archive")
        .await?
        .ok_or_else(|| ApiError::internal("Package archive blob is missing."))?;
    let archive = aurora_registry::Package::read(&bytes, &aurora_registry::Limits::default())
        .map_err(|_| ApiError::internal("Stored package archive is unreadable."))?;
    let manifest: aurora_registry::Manifest = archive
        .manifest(env!("CARGO_PKG_VERSION"))
        .map_err(|_| ApiError::internal("Stored package manifest is unreadable."))?;
    Ok(aurora_registry::webhook::presets(&manifest, &archive)
        .into_iter()
        .find(|(a, _)| a == app_id)
        .map(|(_, p)| p)
        .unwrap_or_default())
}

