/// The strict configuration of an object (unknown keys, a wrong type or a version other than 1 is a
/// `webhook_config_invalid` with the code `invalid_shape`).
pub(crate) fn parse_config(v: Value) -> Result<WebhookConfig, ApiError> {
    serde_json::from_value::<WebhookConfig>(v).map_err(|_| invalid_one("", "invalid_shape"))
}

fn name_ok(n: &str) -> bool {
    let b = n.as_bytes();
    !b.is_empty()
        && b.len() <= 40
        && b[0].is_ascii_lowercase()
        && b.iter()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || *c == b'_')
}

/// A signing secret is 16–256 printable characters.
fn signing_value_ok(s: &str) -> bool {
    (16..=256).contains(&s.chars().count()) && !s.chars().any(char::is_control)
}

fn generate_signing_secret() -> Result<String, ApiError> {
    let mut b = [0u8; 32];
    aws_lc_rs::rand::fill(&mut b)
        .map_err(|_| ApiError::internal("Random generator unavailable."))?;
    Ok(format!("whsec_{}", hex::encode(b)))
}

/// What a body asked for, over the secrets and signing secret the connection has now.
pub(crate) struct Edited {
    pub config: WebhookConfig,
    pub secrets: Map<String, Value>,
    pub signing: Option<String>,
    /// A signing secret generated by this edit: returned once.
    pub generated: Option<String>,
    /// The sealed credential must be rewritten (a secret or the signing secret changed).
    pub secrets_changed: bool,
}

/// Apply a connect or edit body: the configuration, `secret_values` (a value sets, `null` deletes on
/// an edit, an absent name is kept) and `signing_secret`. The result is validated with the crate's
/// rules and the connection's rate ceiling.
pub(crate) fn apply(
    ceiling: (u32, u32),
    body: Value,
    current_secrets: Map<String, Value>,
    current_signing: Option<String>,
    connect: bool,
) -> Result<Edited, ApiError> {
    let Value::Object(mut obj) = body else {
        return Err(invalid_one("", "invalid_shape"));
    };
    let sv = obj.remove("secret_values");
    let sg = obj.remove("signing_secret");
    let mut config = parse_config(Value::Object(obj))?;
    let mut secrets = current_secrets;
    let before = secrets.clone();
    match sv {
        None | Some(Value::Null) => {}
        Some(Value::Object(m)) => {
            for (k, v) in m {
                let path = format!("/secret_values/{k}");
                if !name_ok(&k) {
                    return Err(invalid_one(&path, "slot_name"));
                }
                match v {
                    Value::Null if !connect => {
                        secrets.remove(&k);
                    }
                    Value::String(s) => {
                        if s.len() > SECRET_VALUE_MAX {
                            return Err(invalid_one(&path, "too_large"));
                        }
                        secrets.insert(k, Value::String(s));
                    }
                    _ => return Err(invalid_one(&path, "invalid_shape")),
                }
            }
        }
        Some(_) => return Err(invalid_one("/secret_values", "invalid_shape")),
    }
    let sg = match sg {
        None | Some(Value::Null) => None,
        Some(v) => Some(
            serde_json::from_value::<super::dto::SigningInput>(v)
                .map_err(|_| invalid_one("/signing_secret", "invalid_shape"))?,
        ),
    };
    let mut generated = None;
    let signing = match sg.as_ref().map(|s| (s.mode.as_str(), s.value.as_deref())) {
        None => {
            if connect && config.signing && current_signing.is_none() {
                generated = Some(generate_signing_secret()?);
                generated.clone()
            } else if config.signing {
                current_signing.clone()
            } else {
                None
            }
        }
        Some(("keep", _)) if !connect => current_signing.clone().filter(|_| config.signing),
        Some(("off", _)) if !connect => None,
        Some(("generate", _)) => {
            generated = Some(generate_signing_secret()?);
            generated.clone()
        }
        Some(("provided", Some(v))) => {
            if !signing_value_ok(v) {
                return Err(invalid_one("/signing_secret/value", "slot_limits"));
            }
            Some(v.to_owned())
        }
        Some(_) => return Err(invalid_one("/signing_secret/mode", "invalid_shape")),
    };
    config.signing = signing.is_some();
    let names: Vec<String> = secrets.keys().cloned().collect();
    let mut errs = match aurora_webhook::validate(&config, &names) {
        Ok(_) => Vec::new(),
        Err(e) => e,
    };
    if config.rate.per_minute.is_some_and(|n| n > ceiling.0) {
        errs.push(aurora_webhook::FieldError {
            path: "/rate/per_minute".into(),
            code: "rate_above_ceiling",
        });
    }
    if config.rate.per_day.is_some_and(|n| n > ceiling.1) {
        errs.push(aurora_webhook::FieldError {
            path: "/rate/per_day".into(),
            code: "rate_above_ceiling",
        });
    }
    errs.sort_by(|a, b| a.path.cmp(&b.path));
    errs.dedup();
    if !errs.is_empty() {
        return Err(config_invalid(errs));
    }
    let secrets_changed = secrets != before || signing != current_signing;
    Ok(Edited {
        config,
        secrets,
        signing,
        generated,
        secrets_changed,
    })
}

/// The sealed-credential entries of a send-mode connection beside the URL.
pub(crate) fn with_secrets(
    mut creds: Map<String, Value>,
    secrets: &Map<String, Value>,
    signing: Option<&str>,
) -> Map<String, Value> {
    if secrets.is_empty() {
        creds.remove("secret_values");
    } else {
        creds.insert("secret_values".into(), Value::Object(secrets.clone()));
    }
    match signing {
        Some(s) => {
            creds.insert("signing_secret".into(), Value::String(s.to_owned()));
        }
        None => {
            creds.remove("signing_secret");
        }
    }
    creds
}

// ---- storage ---------------------------------------------------------------------------------

fn seal_context(row: &ConnectionRow) -> SealContext {
    SealContext {
        purpose: Purpose::ConnectionCredentials,
        owner_id: row.id,
        org_id: row.org_id,
        workspace_id: row.workspace_id,
    }
}

/// The sealed credentials of a connection as a JSON object.
pub(crate) async fn open_credentials(
    state: &AppState,
    row: &ConnectionRow,
) -> Result<Map<String, Value>, ApiError> {
    let (cref, _) = repo::credentials_state(&state.pool, row.id)
        .await?
        .ok_or_else(|| ApiError::not_found("Connection not found."))?;
    let sref: SecretRef = cref
        .parse()
        .map_err(|_| ApiError::internal("Stored credentials are unreadable."))?;
    let bytes = state
        .vault
        .open(&seal_context(row), &sref)
        .await
        .map_err(secret_err)?;
    match serde_json::from_slice::<Value>(bytes.expose()) {
        Ok(Value::Object(m)) => Ok(m),
        _ => Err(ApiError::internal("Stored credentials are unreadable.")),
    }
}

pub(crate) async fn org_settings(state: &AppState, org: Uuid) -> Result<Value, ApiError> {
    Ok(
        sqlx::query_scalar::<_, Value>("SELECT settings FROM organizations WHERE id = $1")
            .bind(org)
            .fetch_optional(&state.pool)
            .await
            .map_err(aurora_db::DbError::from)?
            .unwrap_or_else(|| json!({})),
    )
}

pub(crate) fn instance_limits(state: &AppState) -> (u32, u32) {
    let w = &state.ops().outgoing_webhooks;
    (w.per_minute_max, w.per_day_max)
}

fn org_caps(settings: &Value) -> (Option<u32>, Option<u32>) {
    let n = |k: &str| {
        settings
            .pointer(&format!("/outgoing_webhooks/{k}"))
            .and_then(Value::as_u64)
            .and_then(|v| u32::try_from(v).ok())
    };
    (n("per_minute_max"), n("per_day_max"))
}

/// The ceiling a connection's own limits are checked against: the instance's lowered by the org's.
pub(crate) fn ceiling(state: &AppState, settings: &Value) -> (u32, u32) {
    aurora_webhook::ceiling(instance_limits(state), org_caps(settings))
}

fn view_of(
    state: &AppState,
    row: &ConnectionRow,
    settings: &Value,
    config: WebhookConfig,
    secrets: &Map<String, Value>,
) -> WebhookView {
    let eff =
        aurora_webhook::effective_rate(instance_limits(state), org_caps(settings), &config.rate);
    let host = row
        .metadata
        .get("host")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_owned();
    let mut names: Vec<String> = secrets.keys().cloned().collect();
    names.sort();
    WebhookView {
        config,
        host,
        secret_value_names: names,
        effective_rate: EffectiveRateDto {
            per_minute: eff.per_minute,
            per_day: eff.per_day,
            source: match eff.source {
                aurora_webhook::RateSource::Instance => "instance",
                aurora_webhook::RateSource::Org => "org",
                aurora_webhook::RateSource::Connection => "connection",
            }
            .to_owned(),
        },
    }
}

fn secrets_of(creds: &Map<String, Value>) -> Map<String, Value> {
    creds
        .get("secret_values")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default()
}

fn signing_of(creds: &Map<String, Value>) -> Option<String> {
    creds
        .get("signing_secret")
        .and_then(Value::as_str)
        .map(str::to_owned)
}

/// A send-mode connection the caller may manage.
async fn load(
    state: &AppState,
    caller: &Caller,
    id: Uuid,
) -> Result<(ConnectionRow, WebhookConfig), ApiError> {
    let (row, access) = connections::visible(caller, state, id).await?;
    access.require_write()?;
    let config = repo::config(&state.pool, id)
        .await?
        .and_then(|v| serde_json::from_value::<WebhookConfig>(v).ok())
        .ok_or_else(|| ApiError::not_found("This connection is not an outgoing webhook."))?;
    Ok((row, config))
}

